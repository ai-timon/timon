#!/usr/bin/env node
/**
 * Writes `src/product-credential-dirs.ts`: the sign-in folders of the product's
 * own backends, read from the manifests of the official provider plugins
 * (`timon.provider.backends[].credentialDirs`, listed by
 * `orchestrator/builtin-plugins.json`).
 *
 *   node scripts/gen-product-credential-dirs.mjs           # rewrite the file
 *   node scripts/gen-product-credential-dirs.mjs --check   # exit 1 when it is stale
 *
 * Why a generated copy: the daemon reads those folders from the installed
 * manifests, which the published SDK does not ship. Without a copy, the check a
 * provider's own tests run (`runtime.check.declarationProblems`) would let a
 * third party declare `.claude` and only learn at registration that the daemon
 * refuses it. `product-credential-dirs.test.ts` holds the copy to the manifests,
 * and the SDK build refuses a stale one. It lives in the SDK, not in the daemon's tree: a change to
 * an official provider touches its package and this copy, never the core.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PACKAGE = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ORCHESTRATOR = resolve(PACKAGE, '..', '..', 'orchestrator');
export const TARGET = join(PACKAGE, 'src', 'product-credential-dirs.ts');

/**
 * `{ backendId: folders }` in the product's order (`rank`). A backend whose manifest declares an
 * empty list keeps its entry: the daemon's table (`BACKEND_HOME_DIRS`) lists it too, and the two
 * must match key for key.
 */
export function productCredentialDirs(root = ORCHESTRATOR) {
  const { plugins } = JSON.parse(readFileSync(join(root, 'builtin-plugins.json'), 'utf8'));
  const entries = [];
  for (const { source } of plugins) {
    let manifest;
    try {
      manifest = JSON.parse(readFileSync(join(resolve(root, source), 'package.json'), 'utf8'));
    } catch {
      continue;
    }
    const backends = manifest?.timon?.provider?.backends;
    if (!Array.isArray(backends)) continue;
    for (const { id, rank, credentialDirs } of backends) {
      if (Array.isArray(credentialDirs)) entries.push({ id, rank, credentialDirs });
    }
  }
  entries.sort((a, b) => a.rank - b.rank);
  return Object.fromEntries(entries.map(({ id, credentialDirs }) => [id, credentialDirs]));
}

export function render(table) {
  const lines = Object.entries(table).map(([id, dirs]) =>
    `  ${JSON.stringify(id)}: Object.freeze([${dirs.map((d) => JSON.stringify(d)).join(', ')}]),`);
  return `/**
 * GENERATED by \`node scripts/gen-product-credential-dirs.mjs\` (\`packages/sdk\`) from the
 * manifests of the official provider plugins — do not edit by hand.
 *
 * The sign-in folders of the product's own backends, as data: the testing kit hands them
 * to \`credential-home-dirs.ts\` as the table a provider is held to when no daemon installed
 * its own (the published package does not ship the manifests). Inside the daemon, the
 * folders of the manifests the release vouches for win (\`builtin-declarations.ts\`).
 */

export const PRODUCT_BACKEND_HOME_DIRS: Readonly<Record<string, readonly string[]>> = Object.freeze({
${lines.join('\n')}
});
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const wanted = render(productCredentialDirs());
  let current = '';
  try { current = readFileSync(TARGET, 'utf8'); } catch { /* first run */ }
  if (process.argv.includes('--check')) {
    if (current !== wanted) {
      console.error(`${TARGET} is stale: run \`node packages/sdk/scripts/gen-product-credential-dirs.mjs\`.`);
      process.exit(1);
    }
  } else if (current !== wanted) {
    writeFileSync(TARGET, wanted);
    console.log(`wrote ${TARGET}`);
  }
}
